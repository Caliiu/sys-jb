/** Tabela da tela "Como jogar": título, cabeçalho e linhas (texto já formatado). */
export interface HowToPlayTable {
  title: string;
  columns: readonly string[];
  rows: ReadonlyArray<readonly string[]>;
}

/** Combinadas (duque, terno, quadra, quina): palpites → combinações de `size` números. */
export interface CombinationTable {
  title: string;
  /** Números que formam cada combinação (duque = 2, terno = 3…). */
  size: number;
  rows: ReadonlyArray<readonly [guesses: number, combinations: number]>;
}

/** Invertidas: exemplo de palpite (a quantidade de algarismos é o tamanho dele) → inversões de `digits` algarismos. */
export interface InversionTable {
  title: string;
  /** Algarismos de cada inversão (centena = 3, milhar = 4). */
  digits: number;
  rows: ReadonlyArray<readonly [example: string, inversions: number]>;
}

